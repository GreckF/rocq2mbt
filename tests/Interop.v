(* Rocq code calling the MoonBit library tests/moon/mlib through the
   axioms generated by mbti2rocq (tests/gen/Mlib.v). *)

From RocqMbt Require Import Prelude.
From Gen Require Import Mlib.
From Corelib Require Import PrimInt63 PrimFloat PrimString.

Definition i (n : PrimInt63.int) : Int := Int_of_uint63 n.

(* enums with labelled constructor arguments: construction and matching *)
Definition shapes : list Shape :=
  cons (Circle (Double_of_int (i 1))) (cons (Rect (Double_of_int (i 2)) (Double_of_int (i 3))) (cons Dot nil)).
Fixpoint total_area (l : list Shape) : Double :=
  match l with nil => Double_of_int (i 0) | cons s t => PrimFloat.add (area s) (total_area t) end.
Definition kind (s : Shape) : Int :=
  match s with Circle _ => i 0 | Rect w _ => i 1 | Dot => i 2 end.
Definition rect_width (s : Shape) : option Double :=
  match s with Rect w _ => Some w | _ => None end.

(* records: construction, projections, methods with labelled arguments *)
Definition swap (p : Point) : Point := {| Point_x := Point_y p; Point_y := Point_x p |}.
Definition far : Point := Point_scale (swap {| Point_x := i 1; Point_y := Int_neg (i 2) |}) (i 3).
Definition far_norm : Int := Point_norm1 far.
Definition origin_norm : Int := Point_norm1 origin.

(* abstract types, constants *)
Definition counter_value : Int := Counter_value (Counter_new MAX).

(* generic enums, trait-bounded functions (Compare from the Prelude) *)
Fixpoint build {A} `{Compare A} (l : list A) (t : Tree A) : Tree A :=
  match l with nil => t | cons x r => build r (insert t x) end.
Definition sorted_tree : Tree Int := build (cons (i 5) (cons (i 1) (cons (i 3) nil))) Leaf.
(* multi-parameter callback *)
Fixpoint rev_app {A} (l acc : list A) : list A :=
  match l with nil => acc | cons x r => rev_app r (cons x acc) end.
Definition tree_to_list {A} (t : Tree A) : list A :=
  rev_app (fold_tree t nil (fun acc x => cons x acc)) nil.
Definition sorted : list Int := tree_to_list sorted_tree.
Definition tree_sum : Int := fold_tree sorted_tree (i 0) Int_add.

(* returned multi-parameter function *)
Definition add10 : Int -> Int -> Int := make_adder (i 10).
Definition added : Int := add10 (i 1) (i 2).

(* raise functions return Result *)
Definition digit_or_minus1 (s : String) : Int :=
  match parse_digit s with
  | Ok d => d
  | Err (NotADigit _) => Int_neg (i 1)
  | Err EmptyInput => Int_neg (i 2)
  end.

(* a MoonBit trait as a Rocq class; generic code gets the MoonBit bound *)
Definition pretty_pair {A B} `{Pretty A} `{Pretty B} (a : A) (b : B) : String :=
  String_append (pretty a) (String_append (String_of_pstring " "%pstring) (pretty b)).
Definition pretty_test : String := pretty_pair (i 7) far.
Definition pretty_array : String :=
  pretty_all (Array_push (Array_make (i 2) (i 1)) (i 2)).

(* labelled + optional arguments *)
Definition labelled : String := with_label (i 42) (String_of_pstring "answer"%pstring).

Extraction "interop/interop.mbt"
  total_area shapes kind rect_width far far_norm origin_norm counter_value
  sorted tree_sum added digit_or_minus1 pretty_pair pretty_test pretty_array labelled.
